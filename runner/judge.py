"""LLM-судья приёмки: сверка с expected.md ПО СМЫСЛУ, а не подстрокой.

Правило комнаты (`examples/README.md`): «формулировки свободные, факты
(кто · что · когда) должны совпасть». Grep этого не умеет — он сравнивает
буквы. Отсюда два разных вранья:

  * занижение — «Забронировать» против «бронируй» читается как промах;
  * завышение — слово случайно нашлось в соседней записи.

И главное: grep структурно не может проверить ОТРИЦАТЕЛЬНОЕ утверждение
(«новых дублей ни по одному пункту нет»). Судья может — он смотрит на реестр
целиком.

Судья оценивает нашу же работу, поэтому сделан недоверчивым: он не знает,
что реестр «наш», обязан назвать разошедшийся факт, и при сомнении обязан
считать пункт непокрытым.
"""

from __future__ import annotations

import json

from extract import llm

PROMPT = """\
Ты строгий приёмщик. Проверяешь, покрыл ли РЕЕСТР каждый ОЖИДАЕМЫЙ пункт.

Сверка ПО СМЫСЛУ, не по буквам: формулировки свободные, но факты
(кто · что · когда) должны совпасть. «Забронировать зал» и «бронируй зал» —
одно и то же. «до 10.09» и «до 25.09» — разное, это провал.

ПРАВИЛА СУДЕЙСТВА

1. Совпали факты — покрыт. Разошлась дата, владелец или суть — НЕ покрыт.
2. Сомневаешься — считай НЕ покрытым. Строгость важнее доброты.
3. Пункт может быть ОТРИЦАТЕЛЬНЫМ утверждением («новых дублей нет»,
   «из активных ушло»). Проверяй его по реестру целиком: посчитай записи,
   поищи повторы. Отрицательный пункт покрыт, только если утверждение верно.
4. Если пункт говорит «событие, действий не требуется» — достаточно, чтобы
   запись была и была помечена событием.
5. Если пункт помечен «снято/отменено» — запись должна быть в снятых, а не
   в активных.
6. Всегда называй, ЧТО именно разошлось. Пустая строка — только если покрыт.

Пунктов ровно {n}. Верни РОВНО {n} вердиктов, по одному на каждый,
с i от 1 до {n}. Пропустить пункт нельзя — если не понял его, ставь
covered=false и объясни, что непонятно.

ОЖИДАЕМЫЕ ПУНКТЫ
{items}

РЕЕСТР
{registry}

Верни ТОЛЬКО JSON:
{{"verdicts": [{{"i": 1, "covered": true, "diverged": ""}}]}}
"""


def available() -> bool:
    return llm.available()


def judge(items: list[str], registry_text: str) -> list[tuple[bool, str]]:
    """-> список (покрыт, что разошлось) в порядке пунктов.

    При любой поломке возвращает пустой список — вызывающая сторона откатится
    на грубую сверку. Приёмка не должна падать вместе с сетью.
    """
    numbered = "\n".join(f"{i + 1}. {it}" for i, it in enumerate(items))
    try:
        raw = llm.call(PROMPT.format(
            items=numbered, registry=registry_text, n=len(items)))
    except Exception:
        return []

    try:
        start, end = raw.find("{"), raw.rfind("}")
        data = json.loads(raw[start:end + 1])
    except (json.JSONDecodeError, ValueError):
        return []

    verdicts = data.get("verdicts", [])
    by_index = {v.get("i"): v for v in verdicts}

    # недобор вердиктов — вина судьи, а не реестра. Штрафовать за это нельзя:
    # откатываемся на грубую сверку целиком.
    if any(i not in by_index for i in range(1, len(items) + 1)):
        return []

    return [
        (bool(by_index[i].get("covered")),
         (by_index[i].get("diverged") or "").strip())
        for i in range(1, len(items) + 1)
    ]
