"""Распознавание намерения сообщения: закрыть, отменить, перенести.

Отдельный модуль, потому что это чистая функция от строки — тестируется
без графа, без модели и без денег.
"""

from __future__ import annotations

CANCEL = (
    "отменен", "отменён", "отменена", "отменено", "отмена", "отменил",
    "не состоится", "снято", "снята", "отказались", "аннулирован",
)

CLOSE = (
    "закрыто", "закрыт", "закрыли", "готово", "выполнено", "выполнен",
    "сделано", "сделал", "сделала", "уже отправил", "уже отправила",
    "уже сделал", "уже оплатил", "уже продлил", "уже собрал",
)

MOVE = (
    "переносим", "перенесли", "перенос", "переносится", "сдвигаем",
    "апдейт", "вместо этого", "новая дата", "теперь",
)

# Слова самого сигнала не участвуют в сопоставлении: «цифры по отгрузкам уже
# отправил, закрыто» должно искать «цифры отгрузкам», а не «отправил закрыто».
NOISE = set(CANCEL) | set(CLOSE) | set(MOVE) | {
    "уже", "апдейт:", "ваша", "вашему", "запросу", "новая",
}


def detect(text: str) -> str | None:
    """-> 'cancel' | 'close' | 'move' | None"""
    low = text.lower()
    if any(w in low for w in CANCEL):
        return "cancel"
    if any(w in low for w in CLOSE):
        return "close"
    if any(w in low for w in MOVE):
        return "move"
    return None


def strip_noise(text: str) -> str:
    """Убрать служебные слова сигнала перед сопоставлением."""
    low = text.lower()
    for w in sorted(NOISE, key=len, reverse=True):
        low = low.replace(w, " ")
    return low
